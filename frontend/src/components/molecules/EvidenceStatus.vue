<template>
  <section class="evidence-status glass-panel">
    <header>
      <span class="section-kicker">EVIDENCE STATUS</span>
      <h3>What is verified, what is estimated, and what is unknown</h3>
    </header>

    <div class="ev-grid">
      <div class="ev-col verified">
        <h4>Verified source data</h4>
        <p class="hint">Taken directly from the source feed. Not modelled.</p>
        <ul>
          <li><span>Hazard type</span><strong>{{ typeLabel }}</strong></li>
          <li><span>Location</span><strong>{{ incident.location || DASH }}</strong></li>
          <li><span>Coordinates</span><strong>{{ coordText }}</strong></li>
          <li><span>Source</span><strong>{{ incident.source || DASH }}</strong></li>
          <li><span>Detected</span><strong>{{ detectedText }}</strong></li>
        </ul>
      </div>

      <div class="ev-col estimate">
        <h4>Model estimates</h4>
        <p class="hint">Calculated from assumptions. Not measured.</p>
        <ul>
          <li><span>Affected area</span><strong>{{ fmtFixed(incident.affectedArea, 0, ' km²') }}</strong></li>
          <li><span>People exposed</span><strong>{{ fmtCount(incident.affectedPopulation) }}</strong></li>
          <li><span>Risk score</span><strong>{{ scoreText }}</strong></li>
          <li><span>Expansion</span><strong>{{ fmtSigned(incident.trend, 1, ' km²/h') }}</strong></li>
          <li><span>6-hour forecast</span><strong>{{ fmtFixed(incident.forecast6h, 0, ' km²') }}</strong></li>
        </ul>
      </div>

      <div class="ev-col unknown">
        <h4>Unknown or not modelled</h4>
        <p class="hint">Shown as "—" everywhere in TerraGrid.</p>
        <ul v-if="unknownItems.length">
          <li v-for="item in unknownItems" :key="item">{{ item }}</li>
        </ul>
        <p v-else class="hint">Nothing missing from the fields above.</p>
      </div>

      <div class="ev-col ai">
        <h4>AI recommendations</h4>
        <p class="hint">Generated by Gemini. Each one needs an authorized officer's approval.</p>
        <p v-if="hasAi" class="ai-note">Analysis generated. Not verified and not authorized.</p>
        <p v-else class="ai-note">No AI analysis has been generated for this incident yet.</p>
      </div>
    </div>
  </section>
</template>

<script setup lang="ts">
import { computed } from 'vue'
import { fmtFixed, fmtCount, fmtSigned, DASH, impactMetricsFrom } from '@/utils/impactMetrics'

const props = defineProps<{
  incident: any
  deepDossier: any
}>()

const TYPE_LABELS: Record<string, string> = {
  flood: 'Flood', earthquake: 'Earthquake', fire: 'Wildfire', storm: 'Storm',
  volcano: 'Volcano', landslide: 'Landslide', weather: 'Weather',
}

const typeLabel = computed(() => TYPE_LABELS[props.incident.type] || props.incident.type || DASH)

const coordText = computed(() => {
  const c = props.incident.coordinates
  if (!c || c[0] == null || c[1] == null) return DASH
  return `${Number(c[0]).toFixed(4)}, ${Number(c[1]).toFixed(4)}`
})

const detectedText = computed(() => {
  const t = props.incident.detectionTime
  if (!t) return DASH
  const d = new Date(t)
  return isNaN(d.getTime()) ? DASH : d.toLocaleString()
})

const scoreText = computed(() => {
  const s = impactMetricsFrom(props.incident).threatScore
  return s === null ? 'Not scored' : `${s}/100`
})

const hasAi = computed(() => !!props.deepDossier)

// Fields that should have a value but do not. Each one is a gap the officer should know about.
const unknownItems = computed(() => {
  const items: string[] = []
  const m = impactMetricsFrom(props.incident)
  if (m.affectedArea === null) items.push('Affected area: not calculated')
  if (m.affectedPopulation === null) items.push('People exposed: not calculated')
  if (m.threatScore === null) items.push('Risk score: not scored')
  if (m.trend === null) items.push('Expansion rate: not modelled for this hazard type')
  if (m.forecast6h === null) items.push('6-hour forecast: not modelled for this hazard type')
  if (!props.incident.coordinates) items.push('Coordinates: missing from the source')
  if (!props.incident.source) items.push('Source: not recorded')
  return items
})
</script>

