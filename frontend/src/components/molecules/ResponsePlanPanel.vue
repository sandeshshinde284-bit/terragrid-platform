<script setup lang="ts">
import { computed, reactive, ref, watch, onMounted } from 'vue'

const props = defineProps<{
  incidentId: string
  incidentType?: string | null
  incidentLocation?: string | null
}>()

const host = import.meta.env.VITE_API_URL || (window.location.hostname === 'localhost' ? 'http://localhost:8000' : window.location.origin)

const plan = ref<any | null>(null)
const loadError = ref<string | null>(null)
const actionError = ref<string | null>(null)
const busy = ref(false)
const actor = ref('')
const forms = reactive<Record<number, { assignee: string; priority: string; reason: string }>>({})

// Stages: 'overview' shows counts; 'select' picks recommendations; 'review' records decisions; 'tasks' tracks execution; 'summary' shows plan completion.
const stage = ref<'overview' | 'select' | 'review' | 'tasks' | 'summary'>('overview')
// Local to this screen. Not saved: a refresh clears it.
const selected = ref<number[]>([])

const started = computed(() => (plan.value?.review?.approved ?? 0) + (plan.value?.review?.rejected ?? 0) > 0)

// One place decides the button label: no report, no decisions, in review, or some approved.
const primaryLabel = computed(() => {
  if (!plan.value?.report) return 'Generate Crisis Report First'
  if ((plan.value?.review?.approved ?? 0) > 0) return 'Manage Response Plan'
  if (started.value) return 'Continue Response Plan'
  return 'Create Response Plan'
})

const allSelected = computed(() =>
  !!plan.value?.actions?.length && selected.value.length === plan.value.actions.length
)

// Plan name is derived from the incident, not generated by the AI.
const planName = computed(() => {
  const type = props.incidentType ? props.incidentType.charAt(0).toUpperCase() + props.incidentType.slice(1) : 'Incident'
  const place = props.incidentLocation || ''
  return `${place ? place + ' ' : ''}${type} · Response Plan`
})

// Actions shown during review: the ones selected on this screen, plus any already decided.
const reviewActions = computed(() =>
  (plan.value?.actions || []).filter((a: any) => a.decision || isSelected(a.index))
)

const isSelected = (index: number) => selected.value.includes(index)

// Status is derived from saved decisions first, then from the local selection.
const statusLabel = (a: any) => {
  if (a.decision === 'approved') return 'Approved'
  if (a.decision === 'rejected') return 'Rejected'
  return isSelected(a.index) ? 'Selected' : 'Not selected'
}
const statusClass = (a: any) => {
  if (a.decision === 'approved') return 'approved'
  if (a.decision === 'rejected') return 'rejected'
  return isSelected(a.index) ? 'in' : 'out'
}

const toggle = (index: number) => {
  selected.value = isSelected(index)
    ? selected.value.filter(i => i !== index)
    : [...selected.value, index].sort((a, b) => a - b)
}

const selectAll = () => {
  selected.value = (plan.value?.actions || []).map((a: any) => a.index)
}

const clearSelection = () => {
  selected.value = []
}

const primaryAction = () => {
  if (started.value) {
    // Resume: review the actions that are still pending.
    selected.value = (plan.value?.actions || []).filter((a: any) => !a.decision).map((a: any) => a.index)
    stage.value = 'review'
  } else {
    selectAll()
    stage.value = 'select'
  }
}

const goToReview = () => {
  actionError.value = null
  stage.value = 'review'
}

const backToSelect = () => {
  actionError.value = null
  stage.value = 'select'
}

const goToTasks = () => {
  actionError.value = null
  stage.value = 'tasks'
}

const backToReview = () => {
  actionError.value = null
  stage.value = 'review'
}

const goToSummary = () => {
  actionError.value = null
  stage.value = 'summary'
}

const backToTasks = () => {
  actionError.value = null
  stage.value = 'tasks'
}

// Stepper logic for all 4 stages
const stepDone = (n: number) => {
  if (n === 1) return stage.value !== 'overview'
  if (n === 2) return stage.value === 'tasks' || stage.value === 'summary'
  if (n === 3) return stage.value === 'summary'
  return false
}

const stepClass = (n: number) => {
  const stageOrder: Record<string, number> = { overview: 0, select: 1, review: 2, tasks: 3, summary: 4 }
  const currentOrder = stageOrder[stage.value] || 0
  const stepOrder = n
  if (currentOrder === stepOrder) return 'step-active'
  if (currentOrder > stepOrder) return 'step-done'
  return 'step-next'
}

const prioClass = (priority: string) => {
  if (priority === 'IMMEDIATE') return 'p-immediate'
  if (priority === 'HIGH') return 'p-high'
  if (priority === 'STAGED') return 'p-staged'
  return ''
}

const formatTime = (iso: string) => {
  const d = new Date(iso)
  return isNaN(d.getTime()) ? 'time not recorded' : d.toLocaleString()
}

const ensureForm = (index: number) => {
  if (!forms[index]) forms[index] = { assignee: '', priority: 'medium', reason: '' }
}

const canApprove = (index: number) => {
  ensureForm(index)
  return !busy.value && !!actor.value.trim() && !!forms[index].assignee.trim()
}

async function load() {
  loadError.value = null
  try {
    const res = await fetch(`${host}/api/v1/incidents/${props.incidentId}/response/plan`)
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    plan.value = await res.json()
    ;(plan.value.actions || []).forEach((a: any) => ensureForm(a.index))
  } catch (err) {
    loadError.value = 'Could not load the response plan. Try again.'
  }
}

async function decide(index: number, decision: 'approve' | 'reject') {
  if (!plan.value?.report) return
  actionError.value = null
  busy.value = true
  ensureForm(index)
  const f = forms[index]
  try {
    const res = await fetch(`${host}/api/v1/incidents/${props.incidentId}/response/plan/decide`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        actor: actor.value.trim(),
        report_id: plan.value.report.id,
        action_index: index,
        decision,
        assignee: decision === 'approve' ? f.assignee.trim() : undefined,
        priority: f.priority,
        reason: decision === 'reject' ? (f.reason.trim() || undefined) : undefined,
      }),
    })
    if (!res.ok) {
      const body = await res.json().catch(() => ({}))
      actionError.value = typeof body.detail === 'string' ? body.detail : `Could not save the decision (HTTP ${res.status}).`
      return
    }
    await load()
  } catch (err) {
    actionError.value = 'Could not reach the server. The decision was not saved.'
  } finally {
    busy.value = false
  }
}

onMounted(load)
watch(() => props.incidentId, () => {
  stage.value = 'overview'
  selected.value = []
  load()
})
</script>

