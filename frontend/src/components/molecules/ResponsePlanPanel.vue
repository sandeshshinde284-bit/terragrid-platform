<script setup lang="ts">
import { computed, reactive, ref, watch, onMounted } from 'vue'

const props = defineProps<{
  incidentId: string
  incidentType?: string | null
  incidentLocation?: string | null
}>()

const host = import.meta.env.VITE_API_URL || (window.location.hostname === 'localhost' ? 'http://localhost:8000' : window.location.origin)

const plan = ref<any | null>(null)
const loadError = ref<string | null>(null)
const actionError = ref<string | null>(null)
const busy = ref(false)
const actor = ref('')
const forms = reactive<Record<number, { assignee: string; priority: string; reason: string }>>({})

const customPlanName = ref('')
const planDescription = ref('')
const detailsError = ref('')
const detailsSaved = ref(false)
const savedName = ref('')
const savedDescription = ref('')

// Stages: 'overview' (Initial state with 'Create Response Plan' button), 'select' (Plan & Review), 'review' (Review & Approve), 'summary' (Plan Summary)
const stage = ref<'overview' | 'select' | 'review' | 'summary'>('overview')
const selected = ref<number[]>([])

const started = computed(() => (plan.value?.review?.approved ?? 0) + (plan.value?.review?.rejected ?? 0) > 0)

const primaryLabel = computed(() => {
  if (!plan.value?.report) return 'Generate Crisis Report First'
  if ((plan.value?.review?.approved ?? 0) > 0) return 'Manage Response Plan'
  if (started.value) return 'Continue Response Plan'
  return 'Create Response Plan'
})

const allSelected = computed(() =>
  !!plan.value?.actions?.length && selected.value.length === plan.value.actions.length
)

// Actions shown during review: the ones selected on this screen, plus any already decided.
const reviewActions = computed(() =>
  (plan.value?.actions || []).filter((a: any) => a.decision || isSelected(a.index))
)

const statusCount = (key: string) => Number(plan.value?.task_summary?.by_status?.[key] || 0)
const executionPercent = computed(() => {
  const total = Number(plan.value?.task_summary?.approved || 0)
  return total ? Math.round(100 * Number(plan.value?.task_summary?.done || 0) / total) : 0
})
const taskStatusRows = computed(() => [
  { key: 'done', label: 'Completed' }, { key: 'in_progress', label: 'In progress' },
  { key: 'open', label: 'Not started' }, { key: 'blocked', label: 'Blocked' },
].map(item => ({ ...item, count: statusCount(item.key), percent: plan.value?.task_summary?.approved ? Math.round(100 * statusCount(item.key) / plan.value.task_summary.approved) : 0 })))
const blockedTasks = computed(() => (plan.value?.tasks || []).filter((t: any) => t.status === 'blocked' && t.report_version != null))
const statusLabel = (status?: string) => ({ done: 'Completed', in_progress: 'In progress', open: 'Not started', blocked: 'Blocked' } as Record<string, string>)[status || ''] || '—'
const activityLabel = (action: string) => ({ plan_approved: 'Recommendation approved', plan_rejected: 'Recommendation rejected', task_updated: 'Task status updated', plan_details_saved: 'Plan details saved' } as Record<string, string>)[action] || action

const isSelected = (index: number) => selected.value.includes(index)

const toggle = (index: number) => {
  selected.value = isSelected(index)
    ? selected.value.filter(i => i !== index)
    : [...selected.value, index].sort((a, b) => a - b)
}

const selectAll = () => {
  selected.value = (plan.value?.actions || []).map((a: any) => a.index)
}

const clearSelection = () => {
  selected.value = []
}

const primaryAction = () => {
  if (started.value) {
    selected.value = (plan.value?.actions || []).filter((a: any) => !a.decision).map((a: any) => a.index)
    stage.value = 'review'
  } else {
    selectAll()
    stage.value = 'select'
  }
}

const backToOverview = () => {
  actionError.value = null
  stage.value = 'overview'
}

const goToReview = () => {
  actionError.value = null
  stage.value = 'review'
}

const backToSelect = () => {
  actionError.value = null
  stage.value = 'select'
}

const goToSummary = () => {
  actionError.value = null
  stage.value = 'summary'
}

// Stepper logic for 3 stages
const stepDone = (n: number) => {
  if (n === 1) return stage.value === 'review' || stage.value === 'summary' || started.value
  if (n === 2) return stage.value === 'summary'
  return false
}

const stepClass = (n: number) => {
  const stageOrder: Record<string, number> = { overview: 0, select: 1, review: 2, summary: 3 }
  const currentOrder = stageOrder[stage.value] || 0
  if (currentOrder === n) return 'step-active'
  if (currentOrder > n) return 'step-done'
  return 'step-next'
}

const getPriorityClass = (a: any, idx: number) => {
  const p = (a?.priority || '').toUpperCase()
  if (p === 'CRITICAL' || idx === 0) return 'critical'
  if (p === 'HIGH' || idx < 3) return 'high'
  return 'medium'
}

const getPriorityLabel = (a: any, idx: number) => {
  if (a?.priority) return a.priority.toUpperCase()
  if (idx === 0) return 'CRITICAL'
  if (idx < 3) return 'HIGH'
  return 'MEDIUM'
}

const getCategoryStyle = (idx: number) => {
  if (idx === 0) return 'border-color: #3b82f6; color: #60a5fa;'
  if (idx === 1) return 'border-color: #a855f7; color: #c084fc;'
  if (idx === 2) return 'border-color: #f59e0b; color: #fbbf24;'
  return 'border-color: #10b981; color: #34d399;'
}

const getCategoryLabel = (idx: number) => {
  const cats = ['Command & Control', 'Search & Rescue', 'Logistics', 'Medical Support', 'Evacuation Management']
  return cats[idx % cats.length]
}

const formatTime = (iso: string) => {
  if (!iso) return 'Not saved yet'
  const d = new Date(iso)
  return isNaN(d.getTime()) ? 'Invalid date' : d.toLocaleString()
}

async function savePlanDetails() {
  if (!actor.value.trim()) {
    detailsError.value = 'Enter the officer\'s name'
    return
  }

  const nameVal = customPlanName.value.trim() || undefined
  const descVal = planDescription.value.trim() || undefined

  if (nameVal === savedName.value && descVal === savedDescription.value) {
    return // No changes
  }

  detailsError.value = ''
  detailsSaved.value = false

  try {
    const res = await fetch(`${host}/api/v1/incidents/${props.incidentId}/response/plan/details`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        actor: actor.value.trim(),
        name: nameVal,
        description: descVal,
      }),
    })
    if (!res.ok) {
      const body = await res.json().catch(() => ({}))
      detailsError.value = typeof body.detail === 'string' ? body.detail : `Error: HTTP ${res.status}`
      return
    }
    const saved = await res.json()
    savedName.value = nameVal || ''
    savedDescription.value = descVal || ''
    detailsSaved.value = true
    await load()
    setTimeout(() => { detailsSaved.value = false }, 2000)
  } catch (err) {
    detailsError.value = 'Could not save. Check your connection.'
  }
}

const ensureForm = (index: number) => {
  if (!forms[index]) {
    forms[index] = { assignee: 'District Response Team', priority: 'high', reason: '' }
  }
}

async function load() {
  loadError.value = null
  try {
    const res = await fetch(`${host}/api/v1/incidents/${props.incidentId}/response/plan`)
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    plan.value = await res.json()
    ;(plan.value.actions || []).forEach((a: any) => ensureForm(a.index))

    if (selected.value.length === 0 && plan.value?.actions?.length) {
      selectAll()
    }

    // Load saved plan details
    if (plan.value?.plan) {
      customPlanName.value = plan.value.plan.name || ''
      planDescription.value = plan.value.plan.description || ''
      savedName.value = plan.value.plan.name || ''
      savedDescription.value = plan.value.plan.description || ''
    } else if (!customPlanName.value) {
      const type = props.incidentType ? props.incidentType.charAt(0).toUpperCase() + props.incidentType.slice(1) : 'Incident'
      const place = props.incidentLocation || ''
      customPlanName.value = `${place ? place + ' ' : ''}${type} · Response Plan`
    }
  } catch (err) {
    loadError.value = 'Could not load the response plan. Try again.'
  }
}

async function decide(index: number, decision: 'approve' | 'reject') {
  if (!plan.value?.report) return
  if (!actor.value.trim()) {
    actionError.value = 'Enter the officer\'s name to approve or reject.'
    return
  }
  actionError.value = null
  busy.value = true
  ensureForm(index)
  const currentActor = actor.value.trim()
  const f = forms[index]
  try {
    const res = await fetch(`${host}/api/v1/incidents/${props.incidentId}/response/plan/decide`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        actor: currentActor,
        report_id: plan.value.report.id,
        action_index: index,
        decision,
        assignee: decision === 'approve' ? (f.assignee.trim() || 'Response Team') : undefined,
        priority: decision === 'approve' ? (f.priority.toLowerCase() || 'high') : undefined,
        reason: decision === 'reject' ? (f.reason.trim() || 'Not required') : undefined,
      }),
    })
    if (!res.ok) {
      const body = await res.json().catch(() => ({}))
      actionError.value = typeof body.detail === 'string' ? body.detail : `Could not save the decision (HTTP ${res.status}).`
      return
    }
    await load()
  } catch (err) {
    actionError.value = 'Could not reach the server. The decision was not saved.'
  } finally {
    busy.value = false
  }
}

onMounted(load)
watch(() => props.incidentId, () => {
  stage.value = 'overview'
  selected.value = []
  load()
})
</script>

