// Per-tab session state. It survives a page reload in the same tab and is
// cleared when the tab closes. A new tab starts fresh.
//
// Every access is wrapped in try/catch: private windows, blocked storage, or
// a full quota must never break the page. If storage is unavailable, the page
// simply starts from its defaults.

const KEY = 'terragrid.session.v1'

export const readSession = (): Record<string, any> => {
  try {
    return JSON.parse(sessionStorage.getItem(KEY) || '{}') || {}
  } catch {
    return {}
  }
}

export const writeSession = (patch: Record<string, unknown>): void => {
  try {
    sessionStorage.setItem(KEY, JSON.stringify({ ...readSession(), ...patch }))
  } catch {
    // Storage unavailable: keep working without persistence.
  }
}

// AI plans are generated by Gemini, so a fresh request can return different
// wording. Keep the plan the officer already saw for each incident in this tab,
// so a reload shows the same analysis. The newest few are kept to bound size.
const MAX_CACHED_PLANS = 10

export const readCachedPlan = (incidentId: string): any | null => {
  const plans = readSession().aiPlans || {}
  return plans[incidentId]?.plan ?? null
}

export const writeCachedPlan = (incidentId: string, plan: unknown): void => {
  try {
    const plans: Record<string, { plan: unknown; savedAt: number }> = { ...(readSession().aiPlans || {}) }
    plans[incidentId] = { plan, savedAt: Date.now() }
    const kept = Object.entries(plans)
      .sort((a, b) => b[1].savedAt - a[1].savedAt)
      .slice(0, MAX_CACHED_PLANS)
    writeSession({ aiPlans: Object.fromEntries(kept) })
  } catch {
    // Storage unavailable or quota exceeded: the plan is simply not cached.
  }
}
